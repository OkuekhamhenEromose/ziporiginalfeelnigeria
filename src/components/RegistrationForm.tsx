// Define field types
interface BaseField {
  name: string;
  required: boolean;
  icon: IconType;
  type?: string;
  options?: { value: string; label: string }[];
}

interface FieldGroup {
  hStack: BaseField[];
}

type FieldConfig = BaseField | FieldGroup;

const RegistrationForm = () => {
  const { handleSubmit, register, control } = useForm<FormValues>();
  const { createData, data, error, isLoading } = useCreateCustomer();

  const onSubmit = handleSubmit(async (formData) => {
    if (formData.password !== formData.confirmPassword) {
      alert("Passwords do not match!");
      return;
    }
    const payload = {
      name: formData.fullName,
      phone_number: formData.phoneNumber,
      email: formData.email,
      nationality: formData.nationality,
      preferred_destination: formData.preferredDestination,
      password: formData.password,
      travel_date: formData.travelDate,
      username: formData.username,
    };

    await createData(payload);

    if (data) {
      console.log("Form submitted successfully:", data);
      window.location.href = "/login";
    }
    if (error) {
      console.error("Error submitting form:", error);
    }
  });

  const fields: FieldConfig[] = [
    {
      name: "fullName",
      required: true,
      icon: LuUser,
      type: "text",
    },
    {
      hStack: [
        {
          name: "email",
          required: true,
          icon: LuMail,
          type: "email",
        },
        {
          name: "username",
          required: true,
          icon: LuUser,
        },
      ],
    },
    {
      name: "phoneNumber",
      required: true,
      icon: LuPhone,
    },
    {
      name: "nationality",
      required: true,
      icon: LuFlag,
      options: countries,
    },
    {
      hStack: [
        {
          name: "preferredDestination",
          required: true,
          icon: LuPlane,
          options: nigerianStates,
        },
        {
          name: "travelDate",
          required: true,
          icon: LuCalendar,
          type: "date",
        },
      ],
    },
    {
      hStack: [
        {
          name: "password",
          required: true,
          icon: LuLock,
          type: "password",
        },
        {
          name: "confirmPassword",
          required: true,
          icon: LuLock,
          type: "password",
        },
      ],
    },
  ];

  return (
    <Box>
      <Header child="Register with Us" />
      <form className="m-5" onSubmit={onSubmit}>
        <Stack gap="4" align="flex-start">
          {fields.map((field, index) => {
            if ("name" in field) {
              return (
                <RegistrationFormField
                  key={field.name}
                  label={field.name
                    .replace(/([A-Z])/g, " $1")
                    .replace(/^./, (str) => str.toUpperCase())}
                  startElement={<field.icon />}
                  fieldName={field.name as keyof FormValues}
                  required={field.required}
                  fieldType={field?.type}
                  register={register}
                  control={control}
                  options={field?.options}
                />
              );
            } else if ("hStack" in field) {
              return (
                <HStack
                  w={"100%"}
                  align={"flex-end"}
                  flexDirection="row"
                  key={`hstack-${index}`}
                >
                  {field.hStack.map((hField) => (
                    <RegistrationFormField
                      key={hField.name}
                      label={hField.name
                        .replace(/([A-Z])/g, " $1")
                        .replace(/^./, (str) => str.toUpperCase())}
                      startElement={<hField.icon />}
                      fieldName={hField.name as keyof FormValues}
                      required={hField.required}
                      fieldType={hField?.type}
                      register={register}
                      control={control}
                      options={hField?.options}
                    />
                  ))}
                </HStack>
              );
            }
            return null;
          })}
          {isLoading ? (
            <HStack>
              <Button
                type="submit"
                className="text-white btn btn-success"
                borderRadius={3}
              >
                Register
              </Button>
              <Spinner />
            </HStack>
          ) : (
            <Button
              type="submit"
              className="text-white btn btn-success"
              borderRadius={3}
            >
              Register
            </Button>
          )}
        </Stack>
      </form>
    </Box>
  );
};

export default RegistrationForm;